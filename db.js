db.recordFailedLogin = recordFailedLogin;
db.resetFailedLogins = resetFailedLogins;
db.MAX_FAILED_ATTEMPTS = MAX_FAILED_ATTEMPTS;
db.LOCKOUT_MINUTES = LOCKOUT_MINUTES;

